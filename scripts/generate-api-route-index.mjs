import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const serverDir = path.join(root, "src", "server");
const output = path.join(root, "src", "lib", "apiRoutes.generated.ts");
const files = fs.readdirSync(serverDir).filter((name) => name.endsWith("Router.ts") || name === "api.ts");

const prefixes = {
  router: ["/api"], systemRouter: ["/api"], adminRouter: ["/api/admin"], clientRouter: ["/api/client"],
  budgetRouter: ["/api/admin/budgets"], paymentRequestRouter: ["/api/admin/payment-requests"],
  referralRouter: ["/api/admin/referrals"], publicReferralRouter: ["/api/public/referrals"],
  invoiceRouter: ["/api/admin/invoices"], publicInvoiceRouter: ["/api/public/invoices"],
  landingCampaignAdminRouter: ["/api/admin/campaigns"], landingCampaignPublicRouter: ["/api/public/campaigns"],
  publicPushRouter: ["/api/public/push"], exitCouponAdminRouter: ["/api/admin/exit-coupons"], exitCouponPublicRouter: ["/api/public/exit-coupons"],
};

const accessForPath = (route) => route.includes("/admin/") ? "Admin" : route.includes("/client/") ? "Client" : "Public";
const summaryFor = (method, route) => {
  const resource = route.split("/").filter(Boolean).filter((part) => !part.startsWith(":"))[2] || "resource";
  const verbs = { GET: "Reads", POST: "Creates or triggers an action for", PUT: "Replaces or updates", PATCH: "Partially updates", DELETE: "Deletes" };
  return `${verbs[method]} the ${resource.replace(/-/g, " ")} resource.`;
};

const entries = new Map();
for (const file of files) {
  const source = fs.readFileSync(path.join(serverDir, file), "utf8");
  const matcher = /(\w+)\.(get|post|put|patch|delete)\(\s*["']([^"']+)["']/g;
  for (const match of source.matchAll(matcher)) {
    const [, router, rawMethod, suffix] = match;
    for (const prefix of prefixes[router] || []) {
      const route = `${prefix}${suffix === "/" ? "" : suffix}`.replace(/\/+/g, "/");
      const method = rawMethod.toUpperCase();
      entries.set(`${method}:${route}`, { method, path: route, summary: summaryFor(method, route), access: accessForPath(route), source: file });
    }
  }
}

const routes = [...entries.values()].sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));
fs.writeFileSync(output, `// Generated by scripts/generate-api-route-index.mjs. Do not edit manually.\nexport const generatedApiRoutes = ${JSON.stringify(routes, null, 2)} as const;\n`);
console.log(`Generated ${routes.length} API route entries.`);
